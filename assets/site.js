    var all = orderedNotes(D), ix = all.map(function (x) { return x.id; }).indexOf(id);
    var pv = all[ix - 1], nx = all[ix + 1];
    var end = h('<div class="stack"></div>');
    end.innerHTML = '<div class="complete" id="note-complete" hidden><b>Note complete ✓</b><span>Every section ticked. ' + (nx ? 'On to the next one!' : 'You finished the whole notebook!') + '</span></div>' +
      '<nav class="pager" aria-label="Next and previous notes">' +
      (pv ? '<a class="pv" href="' + noteUrl(pv) + '"><small>← Previous' + (pv.module !== n.module ? ' module' : '') + '</small><b>' + esc(pv.title) + '</b></a>' : '') +
      (nx ? '<a class="nx" href="' + noteUrl(nx) + '"><small>Next' + (nx.module !== n.module ? ' module' : '') + ' →</small><b>' + esc(nx.title) + '</b></a>' : '') + '</nav>';
    main.appendChild(end);
    body.appendChild(h('<p class="corner" aria-hidden="true">' + esc(D.site.author) + '</p>'));
    syncChecks();

