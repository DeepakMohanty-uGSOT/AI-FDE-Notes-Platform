  function glossaryPage(D) {
    loadScript(ROOT + 'assets/glossary.js').then(function () {
      var G = (window.AIFDE_GLOSSARY || []).slice().sort(function (a, b) { return a.term.localeCompare(b.term, 'en', { sensitivity: 'base' }); });
      var list = $('#gl'), q = $('#gq'), filt = $('#gfilters'), letters = $('#letters'), mod = 'all';
      var byId = {}; D.notes.forEach(function (n) { byId[n.id] = n; });
      var mods = published(D).filter(function (m) { return G.some(function (x) { return x.n.split('/')[0] === m.slug; }); });
      filt.innerHTML = '<button type="button" data-m="all" aria-pressed="true">All</button>' + mods.map(function (m) { return '<button type="button" data-m="' + m.slug + '" aria-pressed="false">' + esc(m.icon + ' ' + m.title) + '</button>'; }).join('');
      $('#gcount').textContent = G.length + ' terms from ' + Object.keys(G.reduce(function (a, x) { a[x.n] = 1; return a; }, {})).length + ' notes';
      function current() {
        var w = (q.value || '').trim().toLowerCase();
        return G.filter(function (x) {
          if (mod !== 'all' && x.n.split('/')[0] !== mod) return false;
          return !w || (x.term + ' ' + x.def).toLowerCase().indexOf(w) >= 0;
        });
      }
      function draw() {
        var items = current(), html = '', L = '', ls = [];
        items.forEach(function (x) {
          var f = x.term.charAt(0).toUpperCase(); if (!/[A-Z]/.test(f)) f = '#';
          if (f !== L) { if (L) html += '</ul>'; L = f; ls.push(f); html += '<h3 class="letter" id="l-' + (f === '#' ? 'num' : f) + '">' + f + '</h3><ul class="gl-list">'; }
          var n = byId[x.n];
          html += '<li><b>' + esc(x.term) + '</b><span>' + esc(x.def) + '</span>' + (n ? '<a href="' + noteUrl(n) + '#' + x.s + '">from: ' + esc(n.title) + ' →</a>' : '') + '</li>';
        });
        if (L) html += '</ul>';
        list.innerHTML = html || '<p class="empty">No terms match.</p>';
        letters.innerHTML = ls.map(function (f) { return '<a href="#l-' + (f === '#' ? 'num' : f) + '">' + f + '</a>'; }).join('');
      }
      filt.addEventListener('click', function (e) {
        var b = e.target.closest('button'); if (!b) return; mod = b.getAttribute('data-m');
        $$('button', filt).forEach(function (x) { x.setAttribute('aria-pressed', x === b ? 'true' : 'false'); }); draw(); deck();
      });
      q.addEventListener('input', function () { draw(); deck(); });
      draw();

      // flashcards
      var cards = [], ci = 0, cardEl = $('#fc'), front = $('#fc-front'), back = $('#fc-back'), pos = $('#fc-pos');
      function deck(shuffle) {
        cards = current().slice();
        if (shuffle) for (var i = cards.length - 1; i > 0; i--) { var j = Math.floor(Math.random() * (i + 1)); var t = cards[i]; cards[i] = cards[j]; cards[j] = t; }
        ci = 0; show();
      }
      function show() {
        cardEl.classList.remove('flip');
        if (!cards.length) { front.innerHTML = '<b>No cards</b>'; back.innerHTML = ''; pos.textContent = ''; return; }
        var x = cards[ci], n = byId[x.n];
        front.innerHTML = '<small>' + esc(n ? n.title : '') + '</small><b>' + esc(x.term) + '</b><small>tap or press space to flip</small>';
        back.innerHTML = '<b style="font-size:30px">' + esc(x.term) + '</b><p>' + esc(x.def) + '</p>';
        pos.textContent = 'Card ' + (ci + 1) + ' of ' + cards.length;
      }
      cardEl.addEventListener('click', function () { cardEl.classList.toggle('flip'); });
      cardEl.addEventListener('keydown', function (e) { if (e.key === ' ' || e.key === 'Enter') { e.preventDefault(); cardEl.classList.toggle('flip'); } });
      $('#fc-prev').addEventListener('click', function () { if (cards.length) { ci = (ci - 1 + cards.length) % cards.length; show(); } });
      $('#fc-next').addEventListener('click', function () { if (cards.length) { ci = (ci + 1) % cards.length; show(); } });
      $('#fc-shuffle').addEventListener('click', function () { deck(true); });
      document.addEventListener('keydown', function (e) {
        if ($('#flash').hidden || e.target.tagName === 'INPUT') return;
        if (e.key === 'ArrowRight') $('#fc-next').click(); if (e.key === 'ArrowLeft') $('#fc-prev').click();
      });
      var modeBtns = $$('[data-mode]');
      modeBtns.forEach(function (b) {
        b.addEventListener('click', function () {
          var fl = b.getAttribute('data-mode') === 'flash';
          $('#flash').hidden = !fl; $('#gl-wrap').hidden = fl;
          modeBtns.forEach(function (x) { x.setAttribute('aria-pressed', x === b ? 'true' : 'false'); });
          if (fl) deck(true);
        });
      });
      deck();
    }).catch(function () { $('#gl').innerHTML = '<p class="empty">Couldn’t load the glossary. Refresh to try again.</p>'; });
  }

